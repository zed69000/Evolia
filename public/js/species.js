// Anciennes sauvegardes : les plantes n'avaient qu'une couleur et une forme.
const LEGACY_FLOWERS = { '#5B9BD5': 'bourrache', '#EE8FA4': 'mauve', '#EE6A55': 'coquelicot', '#F4C23E': 'bouton-or', '#B48FD8': 'geranium', '#7F8FE0': 'campanule', '#D9739A': 'digitale' };
const LEGACY_BUSHES = { '#EE8FA4': 'eglantier', '#E0603F': 'eglantier', '#C0442F': 'aubepine', '#9E2B25': 'aubepine', '#F4C23E': 'argousier', '#F08A3C': 'argousier', '#5B9BD5': 'prunellier', '#4A5A8A': 'prunellier', '#3A2A40': 'sureau' };

/** Espèce d'une plante, y compris pour les jardins sauvegardés avant l'arrivée des espèces. */
export function speciesOf(p) {
	const v = p.variant ?? {};
	if (v.species && SPECIES_BY_ID[v.species]) return v.species;
	if (p.type === 'herbe') return 'graminees';
	if (p.type === 'arbre') return 'chene';
	if (p.type === 'buisson') return LEGACY_BUSHES[v.berry] ?? 'eglantier';
	if (v.shape === 'tulipe' && v.color === '#F4C23E') return 'tulipe-sauvage';
	return LEGACY_FLOWERS[v.color] ?? 'mauve';
}

/** Une plante est découverte quand un spécimen a fini de pousser ; un milieu quand son décor apparaît. */
function unlocked(s, sp) {
	if (sp.kind === 'animal') return sp.unlock(s);
	if (sp.kind === 'milieu') return has(s, sp.place, sp.decor);
	return nMature(s, sp.place, sp.type, sp.id) >= 1;
}

/** Espèces nouvellement débloquées (et enregistrées dans state.species). */
export function checkSpecies(state) {
	const found = [];
	for (const sp of SPECIES) {
		if (state.species[sp.id] || !unlocked(state, sp)) continue;
		state.species[sp.id] = Date.now();
		found.push(sp);
	}
	return found;
}

/** Lieux ouverts : kilomètres cumulés et espèces découvertes. */
export function placeOpen(state, place) {
	const p = typeof place === 'string' ? PLACE_BY_ID[place] : place;
	return state.totals.distance / 1000 >= p.km && Object.keys(state.species).length >= p.found;
}
